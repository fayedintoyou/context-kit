// Deterministic rendering of a checked map: a Mermaid flowchart and the normalized JSON model.
// Output depends only on the map, the behaviors it cites and the repository's test links (through
// each node's statuses), never on the clock or the machine.
import { fixEdges, problemWording } from './status.mjs';

export const DIAGRAM_START = '<!-- context-kit:diagram:start (generated by `context-kit maps render --write`; do not edit) -->';
export const DIAGRAM_START_PREFIX = '<!-- context-kit:diagram:start';
export const DIAGRAM_END = '<!-- context-kit:diagram:end -->';

// Mermaid node IDs: `n_` plus the kebab-case map ID with `-` as `_`. Map IDs never contain `_`,
// so this is injective, and the prefix keeps clear of keywords such as `end`.
const nodeId = id => `n_${id.replace(/-/g, '_')}`;
// Labels are drawn as written and only ever as text. Mermaid preprocesses the whole source
// (`%%{init}%%` directives, comments) before quoting applies, and reads markup in labels, so
// every character outside a small plain set becomes an entity code (`#37;` for `%`, `#quot;`
// for `"`), and words Mermaid uses as statements (`click`, `style`, ...) never appear verbatim.
// Mermaid decodes the codes back, so the label reads exactly as written.
const PLAIN = /[\p{L}\p{M}\p{N} ,.'!?@()\/+-]/u;
const STATEMENTS = /\b(?:click|style|classDef|class|linkStyle|call|href|callback|subgraph|end|direction|flowchart|graph|accTitle|accDescr)\b/giu;
const code = char => (char === '"' ? '#quot;' : `#${char.codePointAt(0)};`);
const quoted = text => {
  const encoded = [...text].map(char => (PLAIN.test(char) ? char : code(char))).join('');
  return `"${encoded.replace(STATEMENTS, word => code(word[0]) + word.slice(1))}"`;
};
const shapes = {
  start: label => `((${label}))`,
  state: label => `(${label})`,
  choice: label => `{${label}}`,
  end: label => `([${label}])`,
};

// Status classes (design decision 12), in key order. Class names and styles are fixed text; only
// a key entry's wording can come from the map (an issue's finder), and it is quoted like a label.
// Text is dark on every fill, so a dark page theme keeps it readable.
const STATUS_CLASSES = [
  ['works', 'fill:#e5e7eb,stroke:#6b7280,color:#111827', 'Works'],
  ['issue', 'fill:#fee2e2,stroke:#dc2626,color:#111827', null],
  ['fixed', 'fill:#dcfce7,stroke:#16a34a,color:#111827', 'Fixed'],
  ['tested', 'fill:#ffffff,stroke:#6b7280,color:#111827', 'Has linked tests (derived)'],
  ['untested', 'fill:#ffffff,stroke:#6b7280,stroke-dasharray:5 4,color:#111827', 'No tests yet (derived)'],
];
const statusClass = state => `st_${state}`;

// statuses maps a node ID to { declared?, derived }, as maps check reports them; a node is drawn in
// its declared status when it has one, else its derived one (`unknown` is drawn unstyled).
export function mermaid(map, statuses = {}) {
  const lines = ['flowchart TD'];
  for (const node of map.nodes) lines.push(`  ${nodeId(node.id)}${shapes[node.kind](quoted(node.label))}`);
  for (const transition of map.transitions) {
    const edge = transition.when === undefined ? '-->' : `-->|${quoted(transition.when)}|`;
    lines.push(`  ${nodeId(transition.from)} ${edge} ${nodeId(transition.to)}`);
  }
  for (const fix of fixEdges(map)) lines.push(`  ${nodeId(fix.from)} -. ${quoted('with the fix')} .-> ${nodeId(fix.to)}`);
  const shown = id => statuses[id]?.declared?.state ?? statuses[id]?.derived?.state;
  const key = [];
  for (const [state, style, wording] of STATUS_CLASSES) {
    const members = [...new Set(map.nodes.map(node => node.id))].filter(id => shown(id) === state);
    if (!members.length) continue;
    lines.push(`  classDef ${statusClass(state)} ${style}`, `  class ${members.map(nodeId).join(',')} ${statusClass(state)}`);
    // Each way an issue was found gets its own key entry, in node order.
    const wordings = state === 'issue' ? [...new Set(map.nodes.filter(node => shown(node.id) === 'issue').map(node => problemWording(node.status)))] : [wording];
    wordings.forEach((text, index) => key.push(`    key_${state}${index ? `_${index + 1}` : ''}(${quoted(text)}):::${statusClass(state)}`));
  }
  if (key.length) lines.push(`  subgraph status_key[${quoted('Key')}]`, ...key, '  end');
  return lines.join('\n') + '\n';
}

// The generated block written into a map file, in the file's own line endings.
export function diagramBlock(map, eol = '\n', statuses = {}) {
  return [DIAGRAM_START, '```mermaid', ...mermaid(map, statuses).trimEnd().split('\n'), '```', DIAGRAM_END].join(eol);
}

// A citation's pin state: `current` when its behavior's fingerprint is the one pinned, `stale` when
// the behavior changed since, `unpinned` when the map has no pin for it.
export function pinState(pins, id, fingerprint) {
  if (!Object.hasOwn(pins, id)) return 'unpinned';
  return pins[id] === fingerprint ? 'current' : 'stale';
}

// The map's resolved model. resolved maps each citation to its one behavior; statuses are each
// node's { declared?, derived }, as maps check reports them.
export function model(name, title, map, resolved, statuses = {}) {
  const pins = map.pins ?? {};
  const cites = list => (list ?? []).map(id => {
    const behavior = resolved.get(id);
    return { id, kind: behavior.kind, title: behavior.title, fingerprint: behavior.fingerprint, pin: pinState(pins, id, behavior.fingerprint) };
  });
  return {
    map: name, title, source: map.source, scope: map.scope,
    nodes: map.nodes.map(node => ({ id: node.id, kind: node.kind, label: node.label, cites: cites(node.cites), status: statuses[node.id] })),
    transitions: map.transitions.map(transition => ({ from: transition.from, to: transition.to, when: transition.when ?? null, cites: cites(transition.cites) })),
    fixes: fixEdges(map),
  };
}
